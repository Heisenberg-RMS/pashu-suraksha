def chat_with_gemini(user_message: str, language: str = "hi", user_api_key: Optional[str] = None) -> Optional[Dict[str, Any]]:
    """
    Direct zero-dependency integration with Google Gemini Generative AI.
    Provides natural language veterinary conversational support.
    """
    api_key = user_api_key or os.environ.get("GEMINI_API_KEY") or os.environ.get("GOOGLE_API_KEY")
    if not api_key:
        return None
    
    lang_names = {
        "hi": "Hindi (हिन्दी)",
        "mr": "Marathi (मराठी)",
        "te": "Telugu (తెలుగు)",
        "en": "English"
    }
    lang_name = lang_names.get(language, "Hindi")
    
    system_prompt = (
        f"You are Pashu AI Sahayak (पशु एआई सहायक), an empathetic expert Veterinary & Livestock Husbandry AI assisting Indian dairy and livestock farmers, para-vets, and veterinarians. "
        f"Answer the user's question clearly, practically, and empathetically in {lang_name}.\n"
        f"Your expertise comprehensively covers:\n"
        f"1. Livestock Rearing & Calf Care (Newborn calf management, naval dipping, colostrum timing, calf starter, deworming).\n"
        f"2. Feed & Dairy Nutrition (Balanced ration formulation, 2:1 green-to-dry fodder ratio, silage making, concentrate feed, bypass fat, mineral mixture, salt, daily water requirements).\n"
        f"3. Breeding & Reproduction (Heat detection signs, AM-PM AI timing rule, repeat breeding, pregnancy care, drying off, calving assistance, placenta care).\n"
        f"4. Housing & Seasonal Care (Summer heat stress mitigation, winter cold protection, monsoon shed hygiene, ventilation, fly/mosquito vector control).\n"
        f"5. Disease Diagnostics & First Aid (FMD, LSD, Anthrax, HS, BQ, Mastitis, Bloat, Fever, Ticks, Diarrhea, and common health doubts).\n"
        f"6. Clean Milk Production & Drug Withdrawal (Correct milking technique without thumb folding, teat dipping, milk/meat withdrawal clearance periods).\n"
        f"Use simple language easily understood by rural farmers. Use bold headings, bullet points, and practical home dosages."
    )
    
    payload = {
        "contents": [
            {
                "parts": [
                    {"text": f"{system_prompt}\n\nFarmer Query: {user_message}"}
                ]
            }
        ],
        "generationConfig": {
            "temperature": 0.4,
            "maxOutputTokens": 900
        }
    }
    
    models = ["gemini-2.0-flash", "gemini-1.5-flash"]
    for model in models:
        url = f"https://generativelanguage.googleapis.com/v1beta/models/{model}:generateContent?key={api_key}"
        try:
            req = urllib.request.Request(
                url,
                data=json.dumps(payload).encode("utf-8"),
                headers={"Content-Type": "application/json"},
                method="POST"
            )
            with urllib.request.urlopen(req, timeout=8) as res:
                if res.status == 200:
                    resp_data = json.loads(res.read().decode("utf-8"))
                    candidates = resp_data.get("candidates", [])
                    if candidates:
                        parts = candidates[0].get("content", {}).get("parts", [])
                        if parts:
                            reply_text = parts[0].get("text", "").strip()
                            return {
                                "success": True,
                                "title": "Pashu AI Sahayak (✨ Powered by Google Gemini AI)",
                                "intent": "GEMINI_AI_CHAT",
                                "is_emergency": any(w in user_message.lower() for w in ["emergency", "die", "death", "blood", "marr", "mar", "urgent", "आपातकाल", "मृत्यु"]),
                                "reply": reply_text,
                                "suggested_questions": [
                                    "पशु को क्या सुपाच्य आहार दें?",
                                    "क्या यह बीमारी दूसरे पशुओं में भी फैल सकती है?",
                                    "टीकाकरण कब करवाना चाहिए?"
                                ],
                                "language": language,
                                "ai_engine": f"Google Gemini ({model})"
                            }
        except Exception:
            continue
            
    return None


def process_chat_message(user_message: str, language: str = "hi", user_api_key: Optional[str] = None) -> Dict[str, Any]:
    """
    Processes farmer query, attempts Google Gemini Generative AI first if key is available,
    and seamlessly falls back to the calibrated 14-condition veterinary knowledge base.
    """
    # 1. Attempt Google Gemini AI if API key is active
    gemini_reply = chat_with_gemini(user_message, language=language, user_api_key=user_api_key)
    if gemini_reply:
        return gemini_reply

    # 2. Offline Rule-Based Veterinary Knowledge Engine
    msg_clean = user_message.strip().lower()
    
    matched_entry = None
    best_score = 0
    
    for entry in CHATBOT_KNOWLEDGE:
        score = sum(1 for kw in entry["keywords"] if kw.lower() in msg_clean)
        if score > best_score:
            best_score = score
            matched_entry = entry
            
    if not matched_entry or best_score == 0:
        matched_entry = DEFAULT_FALLBACK
        
    # Pick language-appropriate reply
    lang_key = f"reply_{language}"
    reply_text = matched_entry.get(lang_key)
    if not reply_text:
        reply_text = matched_entry.get("reply_hi" if language == "hi" else "reply_en") or matched_entry["reply_en"]
    
    return {
        "success": True,
        "title": matched_entry["title"],
        "intent": matched_entry.get("intent", "GENERAL_ADVISORY"),
        "is_emergency": bool(matched_entry.get("is_emergency", False)),
        "reply": reply_text,
        "suggested_questions": matched_entry.get("suggested_questions", []),
        "language": language,
        "ai_engine": "Pashu Suraksha Veterinary AI Engine"
    }
